// 따라 쓰기 획 데이터 (React 없음 — 음성 목록 스크립트에서도 씀). 좌표는 100×100
export type Pt = [number, number]

// 호(곡선): 각도는 도(°), 0° = 오른쪽, 각도가 커지면 화면에서 시계 방향
export const arc = (cx: number, cy: number, rx: number, ry: number, from: number, to: number): Pt[] => {
  const n = Math.max(2, Math.round(Math.abs(to - from) / 15))
  return Array.from({ length: n + 1 }, (_, i) => {
    const a = ((from + ((to - from) * i) / n) * Math.PI) / 180
    return [cx + rx * Math.cos(a), cy + ry * Math.sin(a)] as Pt
  })
}

