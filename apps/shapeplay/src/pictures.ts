// 해의 햇살(삼각형) 하나: 각도 a(도)
function ray(a: number) {
  const p = (deg: number, rr: number) => `${100 + rr * Math.cos((deg * Math.PI) / 180)} ${100 + rr * Math.sin((deg * Math.PI) / 180)}`
  return `M${p(a - 12, 56)} L${p(a, 92)} L${p(a + 12, 56)} Z`
}
